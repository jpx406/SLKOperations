// An approved checklist or job package as a PDF, filed with the job's attachments when the SDM approves it: the job,
// every question with its answer and remark (for the package, every document with the files uploaded for it), and
// who completed and approved it, with the time of each step.

import { NESR_LOGO_JPEG } from './brandLogo';
import { PdfDoc } from './pdf';

const LOGO = { width: NESR_LOGO_JPEG.width, height: NESR_LOGO_JPEG.height, data: Uint8Array.from(atob(NESR_LOGO_JPEG.base64), (c) => c.charCodeAt(0)) };
const GREY: [number, number, number] = [0.42, 0.42, 0.42];
const WARN: [number, number, number] = [0.72, 0.36, 0];
const BAND: [number, number, number] = [0.93, 0.94, 0.95];
const ACCENT: [number, number, number] = [0.78, 0.83, 0];

/** Date and time in Riyadh, the way every approval is stamped on screen and on paper. */
export const stampText = (iso: string) => `${new Date(iso).toLocaleString('en-GB', { timeZone: 'Asia/Riyadh', day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit' })} Riyadh`;

export interface FormPdfInput {
  title: string; code: string; revision: string;
  job: { ticket_no: string | null; well: string | null; rig: string | null; country: string; unit_number: string | null; start_date: string | null; end_date: string | null };
  /** The R2 folder of a job package. */
  folder?: string;
  sections: Record<string, string>;
  rows: { id: string; section: string; text: string; answer: string; remark?: string | null; flag?: boolean }[];
  completed: { by: string; at: string } | null;
  approval: { by: string; role: string; at: string };
}

export function formPdf(p: FormPdfInput): Uint8Array {
  const doc = new PdfDoc();
  const m = doc.margin, right = doc.width - m, full = right - m;
  doc.rect(m, doc.y - 46, full, 46, [18 / 255, 23 / 255, 31 / 255]);
  const lh = 34, lw = lh * (LOGO.width / LOGO.height);
  doc.jpeg(LOGO, m + 10, doc.y - 40, lw, lh);
  doc.text(m + 20 + lw, doc.y - 20, p.title, { size: 13, bold: true, color: [1, 1, 1] });
  doc.text(m + 20 + lw, doc.y - 36, `${p.code} Rev ${p.revision} · Ticket ${p.job.ticket_no ?? '-'} · ${p.job.country}`, { size: 9, color: [0.8, 0.8, 0.8] });
  doc.text(right - 92, doc.y - 28, 'APPROVED', { size: 14, bold: true, color: ACCENT });
  doc.y -= 60;

  const facts: [string, string | null][] = [['Ticket', p.job.ticket_no], ['Well', p.job.well], ['Rig', p.job.rig], ['Unit', p.job.unit_number], ['Start', p.job.start_date], ['End', p.job.end_date]];
  facts.filter(([, v]) => v).forEach(([k, v], i) => {
    const x = m + (i % 3) * (full / 3);
    if (i % 3 === 0) { doc.need(14); doc.y -= 14; }
    doc.text(x, doc.y, `${k}: `, { size: 8.5, color: GREY });
    doc.text(x + 40, doc.y, String(v).slice(0, 50), { size: 8.5 });
  });
  doc.y -= 10;
  if (p.folder) { doc.para(`Stored in: ${p.folder}`, { size: 8, color: GREY }); doc.y -= 4; }

  const qx = m + 28, ansX = right - 130, qWidth = ansX - qx - 10;
  for (const [key, label] of Object.entries(p.sections)) {
    const rows = p.rows.filter((r) => r.section === key);
    if (!rows.length) continue;
    doc.need(40);
    doc.rect(m, doc.y - 18, full, 18, [0.85, 0.87, 0.89]);
    doc.text(m + 6, doc.y - 13, `${key}  ${label}`, { size: 10, bold: true });
    doc.y -= 22;
    for (const r of rows) {
      doc.need(Math.max(1, Math.ceil(r.text.length / 90)) * 12 + 20);
      const top = doc.y;
      doc.text(m + 4, top - 10, r.id, { size: 8.5, bold: true, color: GREY });
      doc.text(ansX, top - 10, r.answer, { size: 9, bold: true, color: r.flag ? WARN : [0, 0, 0] });
      doc.y = top;
      doc.para(r.text, { x: qx, width: qWidth, size: 8.5 });
      if (r.remark) doc.para(r.remark, { x: qx, width: qWidth, size: 7.5, color: GREY });
      doc.y -= 3;
      doc.line(m, doc.y, right, doc.y, 0.88);
    }
    doc.y -= 8;
  }

  doc.need(60);
  doc.rect(m, doc.y - 48, full, 48, BAND);
  const top = doc.y;
  if (p.completed) doc.text(m + 10, top - 16, `Completed by ${p.completed.by} on ${stampText(p.completed.at)}`, { size: 9 });
  doc.text(m + 10, top - 32, `Approved by ${p.approval.by}${p.approval.role ? ` (${p.approval.role})` : ''} on ${stampText(p.approval.at)}`, { size: 9, bold: true });
  doc.y = top - 58;
  return doc.bytes(`${p.code} Rev ${p.revision} · ticket ${p.job.ticket_no ?? '-'} · approved ${stampText(p.approval.at)} · generated by SLK Operations Hub`);
}
