/** Draws the stack in a box (x, top, w, h in page points, y up) with numbered balloons on the right; returns nothing. */
function schematic(doc: PdfDoc, rows: Row[], kind: DiagramKind, box: { x: number; top: number; w: number; h: number }, opts: { ruler: boolean }) {
  const rulerW = opts.ruler ? 34 : 0, balloonW = 30;
  const W = box.w - rulerW - balloonW;
  const st = layoutStack(rows, FAMILY_OF[kind], W, box.h);
  const prims = st.prims.slice(0, st.prims.length - st.marks.length * 3); // the built-in tags: these sheets draw balloons
  const ox = box.x + rulerW, oy = box.top - (box.h - st.height) / 2;
  const X = (x: number) => ox + x, Y = (y: number) => oy - y;
  for (const g of prims) {
    if (g.t === 'rect') { if (g.fill) doc.rect(X(g.x), Y(g.y + g.h), g.w, g.h, rgb(g.fill)); if (g.outline) doc.box(X(g.x), Y(g.y + g.h), g.w, g.h, 0.23, 0.4); }
    else if (g.t === 'poly') doc.poly(g.pts.map(([px, py]) => [X(px), Y(py)]), rgb(g.fill));
    else if (g.t === 'circle') doc.circle(X(g.cx), Y(g.cy), g.r, g.fill ? rgb(g.fill) : null, rgb(g.stroke));
    else if (g.t === 'image') doc.jpeg(picture(g.key), X(g.x), Y(g.y + g.h), g.w, g.h);
    else if (g.t === 'line') doc.stroke(X(g.x1), Y(g.y1), X(g.x2), Y(g.y2), rgb(g.stroke), g.width);
  }
  // running length at each joint (the drawing is not to length scale, so the scale labels the joints)
  if (opts.ruler) {
    const rx = box.x + rulerW - 5;
    doc.stroke(rx, Y(0), rx, Y(st.height), INK, 0.7);
    doc.text(box.x, Y(0) + 8, 'ft from top', { size: 5.5, color: FAINT });
    let run = 0;
    st.marks.forEach((m, i) => {
      const y = Y(m.y0), lab = run.toFixed(1);
      doc.stroke(rx - 4, y, rx + 4, y, INK, 0.5);
      doc.text(rx - 6 - textWidth(lab, 5.5), y - 2, lab, { size: 5.5, color: MUTED });
      run += rows[i].length_ft ?? 0;
    });
    const end = run.toFixed(1);
    doc.stroke(rx - 4, Y(st.height), rx + 4, Y(st.height), INK, 0.5);
    doc.text(rx - 6 - textWidth(end, 5.5), Y(st.height) - 2, end, { size: 5.5, color: MUTED });
  }
  // balloons, spread so they never overlap, with a leader to the string's axis
  const axis = ox + W / 2, bx = box.x + box.w - 10;
  const ys: number[] = [];
  st.marks.forEach((m) => { let y = Y((m.y0 + m.y1) / 2); if (ys.length && ys[ys.length - 1] - y < 12.5) y = ys[ys.length - 1] - 12.5; ys.push(y); });
  st.marks.forEach((m, i) => {
    const py = Y((m.y0 + m.y1) / 2), by = ys[i];
    doc.stroke(axis + 4, py, bx - 12, py, INK, 0.4);
    doc.stroke(bx - 12, py, bx - 6, by, INK, 0.4);
    doc.circle(bx, by, 5.6, [1, 1, 1], INK, 0.7);
    const s = String(i + 1);
    doc.text(bx - textWidth(s, 6, true) / 2, by - 2.1, s, { size: 6, bold: true, color: INK });
  });
}

interface Col { head: string; w: number; align?: 'l' | 'c' | 'r'; cell: (r: Row, i: number) => { lines: string[]; bold?: boolean; sub?: string[] } }

/** A ruled table; row heights follow the wrapped lines. Returns the y below it. */
function table(doc: PdfDoc, x: number, top: number, cols: Col[], rows: Row[], opts: { size: number; headSize: number; maxBottom: number; head: 'rule' | 'caps' }) {
  let size = opts.size;
  const lead = () => size * 1.22;
  const cellLines = (c: Col, r: Row, i: number) => {
    const v = c.cell(r, i), out: { s: string; bold: boolean; muted: boolean }[] = [];
    for (const l of v.lines) for (const w of wrap(l, c.w - 5, size, v.bold)) out.push({ s: w, bold: !!v.bold, muted: false });
    for (const l of v.sub ?? []) for (const w of wrap(l, c.w - 5, size - 1)) out.push({ s: w, bold: false, muted: true });
    return out;
  };
  const heights = () => rows.map((r, i) => Math.max(...cols.map((c) => cellLines(c, r, i).length)) * lead() + 5);
  let hs = heights();
  const headH = 18;
  // shrink the type if the rows would run past the bottom
  while (size > 5 && top - headH - hs.reduce((a, b) => a + b, 0) < opts.maxBottom) { size -= 0.25; hs = heights(); }
  const W = cols.reduce((a, c) => a + c.w, 0);
  const xs = cols.reduce<number[]>((a, _c, i) => [...a, i ? a[i - 1] + cols[i - 1].w : x], []);
  // header
  if (opts.head === 'rule') doc.stroke(x, top, x + W, top, INK, 1.1);
  cols.forEach((c, i) => {
    const hl = wrap(opts.head === 'caps' ? c.head.toUpperCase() : c.head, c.w - 3, opts.headSize, true);
    hl.slice(0, 2).forEach((l, k) => {
      const tw = textWidth(l, opts.headSize, true), y = top - 7 - k * (opts.headSize + 1.5) - (hl.length === 1 ? 3 : 0);
      doc.text(c.align === 'l' ? xs[i] + 2 : xs[i] + (c.w - tw) / 2, y, l, { size: opts.headSize, bold: true, color: opts.head === 'caps' ? MUTED : INK });
    });
  });
  let y = top - headH;
  doc.stroke(x, y, x + W, y, INK, opts.head === 'rule' ? 0.8 : 1);
  const centers: number[] = [];
  rows.forEach((r, ri) => {
    const h = hs[ri];
    centers.push(y - h / 2);
    cols.forEach((c, i) => {
      const ls = cellLines(c, r, ri);
      const block = ls.length * lead(), start = y - (h - block) / 2 - size * 0.95;
      ls.forEach((l, k) => {
        const s = l.muted ? size - 1 : size, tw = textWidth(l.s, s, l.bold);
        const tx = c.align === 'l' ? xs[i] + 2 : c.align === 'r' ? xs[i] + c.w - 3 - tw : xs[i] + (c.w - tw) / 2;
        doc.text(tx, start - k * lead(), l.s, { size: s, bold: l.bold, color: l.muted ? FAINT : INK });
      });
    });
    y -= h;
    doc.line(x, y, x + W, y, 0.8);
  });
  return { y, xs, W, size, centers };
}

function checkMark(doc: PdfDoc, x: number, y: number, level: Check['level']) {
  if (level === 'ok') { doc.stroke(x, y + 2.6, x + 1.8, y + 0.6, OK, 1); doc.stroke(x + 1.8, y + 0.6, x + 5, y + 4.8, OK, 1); }
  else doc.text(x + 1, y, level === 'warning' ? '!' : 'X', { size: 7, bold: true, color: level === 'warning' ? WARN : BAD });
}

function figures(p: DiagramPdfInput) {
  const rig = p.kind === 'rigup';
  const t = rig ? rigTotals(p.rows) : null, s = rig ? null : stringTotals(p.rows);
  const need = p.facts.siwhp_psi != null ? Math.round(p.facts.siwhp_psi * 1.2) : null;
  const pass = p.checks.filter((c) => c.level === 'ok').length;
  return { t, s, need, pass, total: p.checks.length };
}

const signedText = (s: Signed | null) => (s ? [s.by, stampText(s.at)] : ['', '']);

// ---- A: engineering drawing sheet ----

function engineeringSheet(doc: PdfDoc, p: DiagramPdfInput) {
  const rig = p.kind === 'rigup', form = FORM[p.kind];
  const { t, s, need } = figures(p);
  const L = 22, R = doc.width - 22, B = 40, T = doc.height - 22;
  doc.box(L, B, R - L, T - B, 0.08, 1.4);
  doc.box(L + 3.5, B + 3.5, R - L - 7, T - B - 7, 0.08, 0.5);
  // zones
  for (let i = 0; i < 6; i++) { const zx = L + ((i + 0.5) * (R - L)) / 6; doc.text(zx - 1.5, T + 6, String(i + 1), { size: 5.5, color: FAINT }); }
  'ABCDEFGH'.split('').forEach((z, i) => doc.text(L - 10, T - ((i + 0.5) * (T - B)) / 8 - 2, z, { size: 5.5, color: FAINT }));
  const x0 = L + 9, x1 = R - 9;

  // title block
  const tbB = B + 9, rH = [24, 18, 18, 30], tbT = tbB + rH.reduce((a, b) => a + b, 0);
  const logoW = 72, lab = 50, val = (x1 - x0 - logoW - 3 * lab) / 3;
  doc.box(x0, tbB, x1 - x0, tbT - tbB, 0.08, 1.1);
  const rowTop = (i: number) => tbT - rH.slice(0, i).reduce((a, b) => a + b, 0);
  for (let i = 1; i < 4; i++) doc.stroke(i < 3 ? x0 + logoW : x0, rowTop(i), x1, rowTop(i), INK, 0.5);
  doc.stroke(x0 + logoW, rowTop(0), x0 + logoW, rowTop(3), INK, 0.5);
  const lh = 34, lw = lh * (LOGO.width / LOGO.height);
  doc.jpeg(LOGO, x0 + (logoW - lw) / 2, rowTop(3) + (rH[0] + rH[1] + rH[2] - lh) / 2, lw, lh);
  const cx = (k: number) => x0 + logoW + k * (lab + val); // start of label k (0..2)
  // row 1: title over the first two pairs, then Form
  doc.text(x0 + logoW + 6, rowTop(1) + 8, (rig ? 'RIG UP DIAGRAM · PRESSURE CONTROL' : `SLICKLINE STRING DIAGRAM · BHA · RUN ${p.run_no}`), { size: 11.5, bold: true, color: INK });
  doc.stroke(cx(2), rowTop(0), cx(2), rowTop(1), INK, 0.5);
  const pair = (k: number, row: number, label: string, value: string, bold = false) => {
    const yTop = rowTop(row), yBot = rowTop(row + 1);
    if (k > 0 || row > 0) doc.stroke(cx(k), yTop, cx(k), yBot, INK, 0.5);
    doc.stroke(cx(k) + lab, yTop, cx(k) + lab, yBot, INK, 0.5);
    doc.text(cx(k) + 4, yBot + (yTop - yBot) / 2 - 2, label.toUpperCase(), { size: 5.5, color: MUTED });
    doc.text(cx(k) + lab + 4, yBot + (yTop - yBot) / 2 - 2.5, wrap(value, val - 6, 7.5, bold)[0] ?? '', { size: 7.5, bold, color: INK });
  };
  pair(2, 0, 'Form', rig ? form.code : `${form.code} Rev 2`, true);
  pair(0, 1, 'Client', p.job.client); pair(1, 1, 'Well', p.job.well ?? ''); pair(2, 1, 'Diagram rev', String(p.rev), true);
  pair(0, 2, 'Field / Rig', [p.job.field, p.job.rig].filter(Boolean).join(' / ')); pair(1, 2, 'Job ref.', p.job.ticket_no ?? ''); pair(2, 2, 'Sheet', '1 of 1');
  // row 4: sign-off across the full width
  const sw = (x1 - x0) / 3;
  ([['Prepared', p.prepared], ['Verified', p.verified], ['Approved (SDM)', p.reviewed]] as const).forEach(([k, v], i) => {
    const sx = x0 + i * sw, [by, at] = signedText(v);
    if (i) doc.stroke(sx, rowTop(3), sx, tbB, INK, 0.5);
    doc.text(sx + 4, rowTop(3) - 8, k.toUpperCase(), { size: 5.5, color: MUTED });
    doc.text(sx + 4, rowTop(3) - 18, by || (k.startsWith('Approved') ? 'Not approved' : '-'), { size: 8, bold: !!by, color: by ? INK : FAINT });
    if (at) doc.text(sx + 4, rowTop(3) - 26, at, { size: 6, color: MUTED });
  });

  // body
  const bodyT = T - 12, bodyB = tbT + 10;
  const drawW = rig ? 178 : 150;
  doc.text(x0, bodyT - 6, rig ? 'ASSEMBLY · NOT TO SCALE' : 'SCHEMATIC · JARS OPEN', { size: 6.5, bold: true, color: MUTED });
  if (p.rows.length) schematic(doc, p.rows, p.kind, { x: x0, top: bodyT - 24, w: drawW, h: bodyT - 24 - bodyB - 4 }, { ruler: true });
  const sepX = x0 + drawW + 6;
  doc.stroke(sepX, bodyT, sepX, bodyB, [0.6, 0.64, 0.68], 0.5);
  const lx = sepX + 8, lw2 = x1 - lx;
  doc.text(lx, bodyT - 6, rig ? 'PARTS LIST' : `TOOL STRING · RUN ${p.run_no}`, { size: 6.5, bold: true, color: MUTED });

  const cols: Col[] = rig ? [
    { head: 'Item', w: 18, align: 'c', cell: (_, i) => ({ lines: [String(i + 1)] }) },
    { head: 'Description', w: 0, align: 'l', cell: (r) => ({ lines: [r.name], bold: true }) },
    { head: 'WP / Svc', w: 34, align: 'c', cell: (r) => ({ lines: [rating(r)] }) },
    { head: 'OD in', w: 26, align: 'c', cell: (r) => ({ lines: [f2(r.od_in)] }) },
    { head: 'ID in', w: 28, align: 'c', cell: (r) => ({ lines: [f3(r.id_in)] }) },
    { head: 'Top conn.', w: 47, align: 'c', cell: (r) => ({ lines: connLines(r.top_conn) }) },
    { head: 'Bottom conn.', w: 47, align: 'c', cell: (r) => ({ lines: connLines(r.bottom_conn) }) },
    { head: 'Len ft', w: 30, align: 'r', cell: (r) => ({ lines: [f2(r.length_ft)] }) },
    { head: 'Wt lb', w: 30, align: 'r', cell: (r) => ({ lines: [r.weight_lb != null ? num(r.weight_lb) : '-'] }) },
  ] : [
    { head: 'Item', w: 16, align: 'c', cell: (_, i) => ({ lines: [String(i + 1)] }) },
    { head: 'Description', w: 0, align: 'l', cell: (r) => ({ lines: [r.name], bold: true }) },
    { head: 'Max OD in', w: 30, align: 'c', cell: (r) => ({ lines: [f3(r.od_in)] }) },
    { head: 'ID in', w: 26, align: 'c', cell: (r) => ({ lines: [f3(r.id_in)] }) },
    { head: 'Upper F/N in', w: 31, align: 'c', cell: (r) => ({ lines: [f3(r.fn_in)] }) },
    { head: 'Lower F/N in', w: 31, align: 'c', cell: (r) => ({ lines: [twoNecks(r) != null ? f3(r.fn_lower_in) : '-'] }) },
    { head: 'Top conn.', w: 42, align: 'c', cell: (r) => ({ lines: connLines(r.top_conn) }) },
    { head: 'Bottom conn.', w: 42, align: 'c', cell: (r) => ({ lines: connLines(r.bottom_conn) }) },
    { head: 'Length ft (m)', w: 37, align: 'r', cell: (r) => ({ lines: [f2(r.length_ft)], sub: [r.length_ft != null ? `${(r.length_ft * 0.3048).toFixed(2)} m` : '', ...(r.stroke_ft ? [`+${f2(r.stroke_ft)} open`] : [])].filter(Boolean) }) },
    { head: 'Weight lb (kg)', w: 36, align: 'r', cell: (r) => ({ lines: [r.weight_lb != null ? num(r.weight_lb) : '-'], sub: r.weight_lb != null ? [`${kg(r.weight_lb)} kg`] : [] }) },
  ];
  cols[1].w = lw2 - cols.reduce((a, c) => a + c.w, 0);
  const boxesH = 92, revH = 26;
  const tb = table(doc, lx, bodyT - 14, cols, p.rows, { size: 6.6, headSize: 5.8, maxBottom: bodyB + boxesH + revH + 26, head: 'rule' });
  // totals
  let y = tb.y - 2;
  doc.stroke(lx, y, lx + tb.W, y, INK, 0.9);
  y -= 10;
  if (rig) {
    doc.text(tb.xs[1] + 2, y, 'Totals above the tree', { size: 6.8, bold: true, color: INK });
    const lt = f2(t!.length_ft), wt = num(p.rows.filter((r) => r.kind !== 'tree').reduce((a, r) => a + (r.weight_lb ?? 0), 0));
    doc.text(tb.xs[7] + 27 - textWidth(lt, 6.8, true), y, lt, { size: 6.8, bold: true, color: INK });
    doc.text(tb.xs[8] + 27 - textWidth(wt, 6.8, true), y, wt, { size: 6.8, bold: true, color: INK });
  } else {
    doc.text(tb.xs[1] + 2, y, 'Totals (jars open)', { size: 6.8, bold: true, color: INK });
    const od = f3(s!.max_od_in), lt = f2(s!.length_open_ft), wt = s!.weight_lb != null ? num(s!.weight_lb) : '-';
    doc.text(tb.xs[2] + (30 - textWidth(od, 6.8, true)) / 2, y, od, { size: 6.8, bold: true, color: INK });
    doc.text(tb.xs[8] + 34 - textWidth(lt, 6.8, true), y, lt, { size: 6.8, bold: true, color: INK });
    doc.text(tb.xs[9] + 33 - textWidth(wt, 6.8, true), y, wt, { size: 6.8, bold: true, color: INK });
    const sub1 = `${(s!.length_open_ft * 0.3048).toFixed(2)} m`, sub2 = s!.weight_lb != null ? `${kg(s!.weight_lb)} kg` : '';
    doc.text(tb.xs[8] + 34 - textWidth(sub1, 5.8), y - 8, sub1, { size: 5.8, color: FAINT });
    if (sub2) doc.text(tb.xs[9] + 33 - textWidth(sub2, 5.8), y - 8, sub2, { size: 5.8, color: FAINT });
  }

  // key data and checks
  const bxTop = Math.min(y - 18, bodyB + revH + 10 + boxesH), bw = (tb.W - 8) / 2;
  const keyData: [string, string][] = rig ? [
    ['SIWHP (MPWHP)', p.facts.siwhp_psi != null ? `${num(p.facts.siwhp_psi)} psi` : '-'],
    ['Required WP (x1.2)', need != null ? `${num(need)} psi` : '-'],
    ['Stack working pressure', t!.system_wp != null ? `${num(t!.system_wp)} psi` : '-'],
    ['Wellsite test pressure', need != null ? `${num(need)} psi` : '-'],
    ['Smallest bore', t!.min_id_in != null ? `${f3(t!.min_id_in)} in` : '-'],
    ['Lubricator', `${f2(t!.lubricator_ft)} ft`],
    ['H2S', p.facts.h2s_ppm != null ? `${num(p.facts.h2s_ppm)} ppm` : '-'],
  ] : [
    ['Total depth', `MD ${p.facts.md_ft != null ? num(p.facts.md_ft) : '-'} · TVD ${p.facts.tvd_ft != null ? num(p.facts.tvd_ft) : '-'} ft`],
    ['Min. restriction', p.facts.min_restriction_in != null ? `${f3(p.facts.min_restriction_in)} in` : '-'],
    ['Max tool OD', `${f3(s!.max_od_in)} in`],
    ['Length closed / open', `${f2(s!.length_ft)} / ${f2(s!.length_open_ft)} ft`],
    ['Weight above the jar', s!.weight_above_jar_lb != null ? `${num(s!.weight_above_jar_lb)} lb` : '-'],
    ['Wire', p.facts.wire_in != null ? `${p.facts.wire_in} in` : '-'],
  ];
  doc.box(lx, bxTop - boxesH, bw, boxesH, 0.08, 0.6);
  doc.text(lx + 5, bxTop - 9, 'KEY DATA', { size: 6, bold: true, color: MUTED });
  keyData.forEach(([k, v], i) => {
    const ky = bxTop - 20 - i * 10;
    doc.text(lx + 5, ky, k, { size: 6.6, color: MUTED });
    doc.text(lx + bw - 5 - textWidth(v, 6.6, true), ky, v, { size: 6.6, bold: true, color: INK });
  });
  const cxL = lx + bw + 8;
  doc.box(cxL, bxTop - boxesH, bw, boxesH, 0.08, 0.6);
  doc.text(cxL + 5, bxTop - 9, 'CHECKS', { size: 6, bold: true, color: MUTED });
  let cy = bxTop - 20;
  for (const c of p.checks) {
    const lines = wrap(c.text, bw - 22, 5.9);
    if (cy - lines.length * 7 < bxTop - boxesH + 4) { doc.text(cxL + 14, cy, `+ ${p.checks.length - p.checks.indexOf(c)} more on screen`, { size: 5.8, color: FAINT }); break; }
    checkMark(doc, cxL + 5, cy, c.level);
    lines.forEach((l, k) => doc.text(cxL + 14, cy - k * 7, l, { size: 5.9, color: INK }));
    cy -= lines.length * 7 + 2.5;
  }
  // revision line
  const rvT = bodyB + revH;
  const rc = [30, 70, tb.W - 30 - 70 - 70, 70];
  const rx = rc.reduce<number[]>((a, _w, i) => [...a, i ? a[i - 1] + rc[i - 1] : lx], []);
  doc.rect(lx, rvT - 11, tb.W, 11, [0.93, 0.94, 0.95]);
  doc.box(lx, bodyB, tb.W, revH, 0.08, 0.6);
  doc.stroke(lx, rvT - 11, lx + tb.W, rvT - 11, INK, 0.5);
  rx.slice(1).forEach((x) => doc.stroke(x, rvT, x, bodyB, INK, 0.5));
  ['Rev', 'Date', 'Status', 'By'].forEach((h, i) => doc.text(rx[i] + 3, rvT - 8, h, { size: 6, bold: true, color: INK }));
  const last = p.reviewed ?? p.verified ?? p.prepared;
  const status = p.status === 'reviewed' ? 'Approved by the SDM' : p.verified ? 'Verified, waiting for SDM approval' : p.status === 'sent' ? 'Sent for review' : 'Draft';
  [String(p.rev), last ? stampText(last.at).replace(/,? \d\d:\d\d.*$/, '') : '-', status, last?.by ?? '-'].forEach((v, i) => doc.text(rx[i] + 3, bodyB + 4, wrap(v, rc[i] - 6, 6.5)[0] ?? '', { size: 6.5, color: INK }));
  doc.y = B;
}

// ---- B: data sheet ----

function dataSheet(doc: PdfDoc, p: DiagramPdfInput) {
  const rig = p.kind === 'rigup', form = FORM[p.kind];
  const { t, s, need, pass, total } = figures(p);
  const L = 32, R = doc.width - 32, T = doc.height - 30;
  // header
  const lh = 32, lw = lh * (LOGO.width / LOGO.height);
  doc.jpeg(LOGO, L, T - lh, lw, lh);
  doc.text(L + lw + 12, T - 16, rig ? 'Rig Up Diagram' : `Slickline String Diagram · Run ${p.run_no}`, { size: 18, bold: true, color: INK });
  doc.text(L + lw + 12, T - 29, [p.job.client, p.job.well, [p.job.field, p.job.rig].filter(Boolean).join(' / '), p.job.date].filter(Boolean).join(' · '), { size: 8, color: MUTED });
  const code = rig ? form.code : `${form.code} Rev 2`;
  doc.text(R - textWidth(code, 10, true), T - 9, code, { size: 10, bold: true, color: INK });
  const rv = `Diagram Rev ${p.rev}`;
  doc.text(R - textWidth(rv, 8), T - 20, rv, { size: 8, color: MUTED });
  const stat = p.status === 'reviewed' ? 'APPROVED' : p.verified ? 'VERIFIED' : p.status === 'sent' ? 'SENT' : 'DRAFT';
  const sc: RGB = p.status === 'reviewed' ? OK : p.verified || p.status === 'sent' ? WARN : FAINT;
  const sw = textWidth(stat, 6.5, true) + 12;
  doc.stroke(R - sw, T - 35, R, T - 35, sc, 0.8); doc.stroke(R - sw, T - 25, R, T - 25, sc, 0.8);
  doc.stroke(R - sw, T - 35, R - sw, T - 25, sc, 0.8); doc.stroke(R, T - 35, R, T - 25, sc, 0.8);
  doc.text(R - sw + 6, T - 32.5, stat, { size: 6.5, bold: true, color: sc });
  doc.rect(L, T - 46, R - L, 2.2, INK);

  // key figures
  const k: [string, string, string][] = rig ? [
    ['Stack WP', t!.system_wp != null ? num(t!.system_wp) : '-', ' psi'], ['Test pressure', need != null ? num(need) : '-', ' psi'],
    ['Smallest bore', t!.min_id_in != null ? f3(t!.min_id_in) : '-', ' in'], ['Lubricator', f2(t!.lubricator_ft), ' ft'],
    ['Length above tree', f2(t!.length_ft), ' ft'], ['Checks', `${pass} / ${total}`, ' pass'],
  ] : [
    ['Length, jars open', f2(s!.length_open_ft), ' ft'], ['Weight', s!.weight_lb != null ? num(s!.weight_lb) : '-', ' lb'],
    ['Max OD', f3(s!.max_od_in), ' in'], ['Min. restriction', p.facts.min_restriction_in != null ? f3(p.facts.min_restriction_in) : '-', ' in'],
    ['Total depth MD', p.facts.md_ft != null ? num(p.facts.md_ft) : '-', ' ft'], ['Checks', `${pass} / ${total}`, ' pass'],
  ];
  const kT = T - 56, kH = 34, gap = 6, kW = (R - L - gap * 5) / 6;
  k.forEach(([label, v, u], i) => {
    const kx = L + i * (kW + gap);
    doc.rect(kx, kT - kH, kW, kH, CARD);
    doc.text(kx + 6, kT - 10, label.toUpperCase(), { size: 5.6, color: MUTED });
    doc.text(kx + 6, kT - 26, v, { size: 12.5, bold: true, color: INK });
    doc.text(kx + 6 + textWidth(v, 12.5, true), kT - 26, u, { size: 7, color: MUTED });
  });

  // body: schematic panel and table
  const bodyT = kT - kH - 14, footH = 54, bodyB = 40 + footH + 10;
  const panelW = rig ? 214 : 168;
  // white panel with a fine edge: the part pictures are JPEGs on white, so a tinted panel would show their boxes
  doc.box(L, bodyB, panelW, bodyT - bodyB, 0.82, 0.6);
  if (p.rows.length) schematic(doc, p.rows, p.kind, { x: L + 8, top: bodyT - 10, w: panelW - 16, h: bodyT - bodyB - 20 }, { ruler: false });
  const tx = L + panelW + 14, tw = R - tx;
  const nCol: Col = { head: '#', w: 18, align: 'c', cell: (_, i) => ({ lines: [String(i + 1)] }) };
  const cols: Col[] = rig ? [
    nCol,
    { head: 'Part', w: 0, align: 'l', cell: (r) => ({ lines: [r.name], bold: true, sub: [r.kind === 'tree' ? 'Client equipment' : rating(r)] }) },
    { head: 'OD in', w: 28, align: 'c', cell: (r) => ({ lines: [f2(r.od_in)] }) },
    { head: 'ID in', w: 30, align: 'c', cell: (r) => ({ lines: [f3(r.id_in)] }) },
    { head: 'Top', w: 50, align: 'c', cell: (r) => ({ lines: connLines(r.top_conn) }) },
    { head: 'Bottom', w: 50, align: 'c', cell: (r) => ({ lines: connLines(r.bottom_conn) }) },
    { head: 'Len ft', w: 30, align: 'r', cell: (r) => ({ lines: [f2(r.length_ft)] }) },
  ] : [
    nCol,
    { head: 'Tool', w: 0, align: 'l', cell: (r) => ({ lines: [r.name], bold: true, sub: [`${r.top_conn ?? '-'} > ${r.bottom_conn ?? '-'}`] }) },
    { head: 'Max OD', w: 31, align: 'c', cell: (r) => ({ lines: [f3(r.od_in)] }) },
    { head: 'ID', w: 27, align: 'c', cell: (r) => ({ lines: [f3(r.id_in)] }) },
    { head: 'Upper F/N', w: 33, align: 'c', cell: (r) => ({ lines: [f3(r.fn_in)] }) },
    { head: 'Lower F/N', w: 33, align: 'c', cell: (r) => ({ lines: [twoNecks(r) != null ? f3(r.fn_lower_in) : '-'] }) },
    { head: 'Len ft', w: 34, align: 'r', cell: (r) => ({ lines: [f2(r.length_ft)], sub: r.stroke_ft ? [`+${f2(r.stroke_ft)} open`] : [] }) },
    { head: 'Wt lb', w: 32, align: 'r', cell: (r) => ({ lines: [r.weight_lb != null ? num(r.weight_lb) : '-'] }) },
  ];
  cols[1].w = tw - cols.reduce((a, c) => a + c.w, 0);
  const tb = table(doc, tx, bodyT, cols, p.rows, { size: 7, headSize: 6, maxBottom: bodyB + 60, head: 'caps' });
  // ring the item numbers, matching the balloons on the schematic
  tb.centers.forEach((cy) => doc.circle(tx + 9, cy + 0.2, 5.4, null, INK, 0.6));
  let y = tb.y - 2;
  doc.stroke(tx, y, tx + tb.W, y, INK, 1);
  y -= 10;
  doc.text(tb.xs[1] + 2, y, rig ? 'Totals above the tree' : 'Totals · jars open', { size: 7, bold: true, color: INK });
  if (rig) { const lt = f2(t!.length_ft); doc.text(tx + tb.W - 3 - textWidth(lt, 7, true), y, lt, { size: 7, bold: true, color: INK }); }
  else {
    const lt = f2(s!.length_open_ft), wt = s!.weight_lb != null ? num(s!.weight_lb) : '-', od = f3(s!.max_od_in);
    doc.text(tb.xs[2] + (31 - textWidth(od, 7, true)) / 2, y, od, { size: 7, bold: true, color: INK });
    doc.text(tb.xs[6] + 31 - textWidth(lt, 7, true), y, lt, { size: 7, bold: true, color: INK });
    doc.text(tx + tb.W - 3 - textWidth(wt, 7, true), y, wt, { size: 7, bold: true, color: INK });
  }
  // checks: every one that is not a pass, then a one-line summary of the passes
  y -= 18;
  const bad = p.checks.filter((c) => c.level !== 'ok');
  doc.text(tx, y, 'CHECKS', { size: 6, bold: true, color: MUTED });
  y -= 10;
  for (const c of bad) {
    const lines = wrap(c.text, tb.W - 14, 6.6);
    if (y - lines.length * 8 < bodyB) break;
    checkMark(doc, tx, y, c.level);
    lines.forEach((l, i) => doc.text(tx + 10, y - i * 8, l, { size: 6.6, color: INK }));
    y -= lines.length * 8 + 3;
  }
  const passText = `${pass} of ${total} pass: ${p.checks.filter((c) => c.level === 'ok').map((c) => c.text.replace(/\.$/, '')).join(' · ') || '-'}`;
  for (const [i, l] of wrap(passText, tb.W - 14, 6.2).entries()) { if (y < bodyB) break; if (!i) checkMark(doc, tx, y, 'ok'); doc.text(tx + 10, y, l, { size: 6.2, color: MUTED }); y -= 7.5; }

  // sign-off strip
  const fy = 40 + footH;
  doc.rect(L, fy, R - L, 0.9, INK);
  const cells: [string, string, string][] = [
    ['Prepared by', ...signedText(p.prepared)] as [string, string, string], ['Verified by', ...signedText(p.verified)] as [string, string, string],
    ['Approved by (SDM)', ...signedText(p.reviewed)] as [string, string, string], ['Job ref.', p.job.ticket_no ?? '-', 'Sheet 1 of 1'],
  ];
  const cw = [(R - L) * 0.29, (R - L) * 0.29, (R - L) * 0.29, (R - L) * 0.13];
  let cxp = L;
  cells.forEach(([label, by, at], i) => {
    const w = cw[i] - 10;
    doc.text(cxp, fy - 12, label.toUpperCase(), { size: 5.8, color: MUTED });
    doc.text(cxp, fy - 28, by || (i === 2 ? 'Not approved' : '-'), { size: 9.5, bold: !!by, color: by ? INK : FAINT });
    doc.stroke(cxp, fy - 33, cxp + w, fy - 33, [0.6, 0.64, 0.68], 0.5);
    if (at) doc.text(cxp, fy - 42, at, { size: 6.2, color: FAINT });
    cxp += cw[i];
  });
  doc.y = 40;
}
