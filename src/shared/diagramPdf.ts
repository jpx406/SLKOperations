type RGB = [number, number, number];
const INK: RGB = [0.08, 0.1, 0.12], MUTED: RGB = [0.31, 0.34, 0.38], FAINT: RGB = [0.42, 0.45, 0.5];
const CARD: RGB = [0.953, 0.961, 0.969], OK: RGB = [0.11, 0.42, 0.27], WARN: RGB = [0.62, 0.42, 0], BAD: RGB = [0.7, 0.14, 0.16];
const rgb = (hex: string): RGB => { const n = parseInt(hex.slice(1), 16); return [((n >> 16) & 255) / 255, ((n >> 8) & 255) / 255, (n & 255) / 255]; };
const LOGO = { width: NESR_LOGO_DARK_JPEG.width, height: NESR_LOGO_DARK_JPEG.height, data: Uint8Array.from(atob(NESR_LOGO_DARK_JPEG.base64), (c) => c.charCodeAt(0)) };
// decoded once per worker and reused, so the PDF stores each picture once
const pictures = new Map<PictureKey, { width: number; height: number; data: Uint8Array }>();
const picture = (k: PictureKey) => {
  let pic = pictures.get(k);
  if (!pic) { const j = PICTURES[k]; pic = { width: j.width, height: j.height, data: Uint8Array.from(atob(j.base64), (c) => c.charCodeAt(0)) }; pictures.set(k, pic); }
  return pic;
};

const f2 = (n: number | null | undefined) => (n == null ? '-' : n.toFixed(2));
const f3 = (n: number | null | undefined) => (n == null ? '-' : n.toFixed(3));
const kg = (lb: number) => (lb * 0.4536).toFixed(1);
const num = (n: number) => n.toLocaleString('en-US', { maximumFractionDigits: 0 });
const connLines = (c: string | null) => { if (!c) return ['-']; const m = /^(.*?)\s*(\(.+\).*)$/.exec(c); return m ? [m[1], m[2]] : [c]; };
const rating = (r: Row) => (r.rating_psi ? `${r.rating_psi / 1000}K${r.service === 'h2s' ? ' H2S' : ''}` : '-');
const twoNecks = (r: Row) => r.fn_lower_in;

export interface Signed { by: string; at: string }
export interface DiagramPdfInput {
  style: SheetStyle;
  kind: DiagramKind; run_no: number; rev: number; status: DiagramStatus; rows: Row[];
  job: { client: string; well: string | null; field: string | null; rig: string | null; unit_number: string | null; date: string | null; ticket_no: string | null; drss_no: string | null };
  facts: { siwhp_psi: number | null; h2s_ppm: number | null; min_restriction_in: number | null; wire_in: number | null; md_ft: number | null; tvd_ft: number | null };
  checks: Check[];
  prepared: Signed | null; verified: Signed | null; reviewed: Signed | null;
}

export function diagramPdf(p: DiagramPdfInput): Uint8Array {
  const doc = new PdfDoc();
  if (p.style === 'data') dataSheet(doc, p); else engineeringSheet(doc, p);
  const form = FORM[p.kind];
  return doc.bytes(`${form.code}${p.kind === 'toolstring' ? ' Rev 2' : ''} · diagram Rev ${p.rev} · ${p.job.well ?? ''} · ticket ${p.job.ticket_no ?? '-'} · generated by SLK Operations Hub`);
}

