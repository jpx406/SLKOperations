// layouts the owner approved on 2026-11-09 (design/diagram-mockups):
//   'sheet': engineering drawing sheet. Frame with zones, title block with sign-off, parts list, key data, checks,
//            revision line, and the schematic with a running-length scale and numbered balloons.
//   'data':  data sheet. Header band with status, six key figures, schematic panel beside the parts table, sign-off strip.

