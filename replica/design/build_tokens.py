#!/usr/bin/env python3
"""Generate tokens.css and tailwind.theme.css from tokens.json, then check contrast for every theme.

    python build_tokens.py            # writes files, exits 1 if any pair fails WCAG AA
    python build_tokens.py --check    # contrast only

Standard library only. Run it after every token change, including the rebrand.
"""

import json
import os
import sys
import tempfile

import contrast

HERE = os.path.dirname(os.path.abspath(__file__))


def load():
    with open(os.path.join(HERE, "tokens.json"), encoding="utf-8") as fh:
        return json.load(fh)


def css_vars(colors, indent="  "):
    return "\n".join(f"{indent}--color-{k}: {v};" for k, v in colors.items())


def build_css(t):
    lines = [
        "/* Generated by build_tokens.py from tokens.json — do not edit by hand. */",
        ":root {",
        "  color-scheme: dark;",
        css_vars(t["color"]),
    ]
    for name, fam in t["font"].items():
        if not name.startswith("_"):
            lines.append(f"  --font-{name}: {fam};")
    for name, spec in t["type"].items():
        lines.append(f"  --text-{name}: {spec['size']}px;")
        lines.append(f"  --text-{name}--line-height: {spec['line']}px;")
        lines.append(f"  --text-{name}--font-weight: {spec['weight']};")
        if "tracking" in spec:
            lines.append(f"  --text-{name}--letter-spacing: {spec['tracking']};")
    for name, px in t["radius"].items():
        lines.append(f"  --radius-{name}: {px}px;")
    lines.append(f"  --shadow-card: {t['shadow']['card']};")
    lines.append(f"  --shadow-pop: {t['shadow']['pop']};")
    for name, val in t["motion"].items():
        lines.append(f"  --motion-{name}: {val};")
    for name, val in t["layout"].items():
        if isinstance(val, (int, float)):
            lines.append(f"  --layout-{name}: {val}px;")
    for name, val in t["z"].items():
        lines.append(f"  --z-{name}: {val};")
    lines.append("}")
    for theme, colors in t.get("themes", {}).items():
        # also matches any container, so the /design page can show both themes side by side
        lines += ["", f':root[data-theme="{theme}"], [data-theme="{theme}"] {{', f"  color-scheme: {theme};", css_vars(colors)]
        if theme == "light":
            lines.append(f"  --shadow-card: {t['shadow']['light-card']};")
            lines.append(f"  --shadow-pop: {t['shadow']['light-pop']};")
        lines.append("}")
    for name, d in t.get("density", {}).items():
        # bigger controls and text for touch screens; set by the app on <html data-density="touch">
        lines += ["", f':root[data-density="{name}"] {{']
        for k, px in d.get("layout", {}).items():
            lines.append(f"  --layout-{k}: {px}px;")
        for k, spec in d.get("type", {}).items():
            lines.append(f"  --text-{k}: {spec['size']}px;")
            lines.append(f"  --text-{k}--line-height: {spec['line']}px;")
        lines.append("}")
    lines += [
        "",
        "@media (prefers-reduced-motion: reduce) {",
        "  :root { --motion-fast: 0ms; --motion-base: 0ms; --motion-slow: 0ms; }",
        "}",
        "",
    ]
    return "\n".join(lines)


def build_tailwind(t):
    """Tailwind v4 @theme block mapping utilities to the CSS variables (bg-surface, text-muted, rounded-md ...)."""
    lines = [
        "/* Generated by build_tokens.py — Tailwind v4. Import after tokens.css:",
        '   @import "tailwindcss"; @import "./tokens.css"; @import "./tailwind.theme.css"; */',
        "@theme inline {",
        "  --color-*: initial;",
    ]
    for k in t["color"]:
        lines.append(f"  --color-{k}: var(--color-{k});")
    for name in t["font"]:
        if not name.startswith("_"):
            lines.append(f"  --font-{name}: var(--font-{name});")
    for name, spec in t["type"].items():
        lines.append(f"  --text-{name}: var(--text-{name});")
        lines.append(f"  --text-{name}--line-height: var(--text-{name}--line-height);")
    lines.append("  --radius-*: initial;")
    for name in t["radius"]:
        lines.append(f"  --radius-{name}: var(--radius-{name});")
    lines.append("  --shadow-card: var(--shadow-card);")
    lines.append("  --shadow-pop: var(--shadow-pop);")
    lines.append("  --spacing: 4px;")
    for name, px in t["layout"]["breakpoints"].items():
        lines.append(f"  --breakpoint-{name}: {px}px;")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def check_all(t):
    failed = False
    themes = {"dark (default)": t["color"]}
    themes.update({k: v for k, v in t.get("themes", {}).items()})
    for name, colors in themes.items():
        print(f"\n== {name} ==")
        missing = set(t["color"]) - set(colors)
        if missing:
            print(f"  theme is missing tokens: {sorted(missing)}")
            failed = True
        with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as fh:
            json.dump({"color": colors, "pairs": t["pairs"]}, fh)
            path = fh.name
        try:
            failed |= contrast.main([path]) != 0
        finally:
            os.unlink(path)
    return failed


def main(argv):
    t = load()
    if "--check" not in argv:
        with open(os.path.join(HERE, "tokens.css"), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(build_css(t))
        with open(os.path.join(HERE, "tailwind.theme.css"), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(build_tailwind(t))
        print("wrote tokens.css, tailwind.theme.css")
    return 1 if check_all(t) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
