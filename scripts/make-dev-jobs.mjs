// Writes scripts/dev-jobs.sql: about 120 fake Saudi Arabia jobs across 2026 so the analytics screens have
// something to show locally. Deterministic (seeded), fake wells and tickets, never for the remote database.
// node scripts/make-dev-jobs.mjs && npx wrangler d1 execute slkops-db --local --file scripts/dev-jobs.sql
import fs from 'node:fs';

let seed = 20261025;
const rnd = () => ((seed = (seed * 1103515245 + 12345) % 2 ** 31) / 2 ** 31);
const pick = (a) => a[Math.floor(rnd() * a.length)];
const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

const seedSql = fs.readFileSync(new URL('../replica/migrations/0002_seed.sql', import.meta.url), 'utf8');
const services = [...seedSql.matchAll(/INTO service_profiles \([^)]*\) VALUES \('([^']+)'/g)].map((m) => m[1]);
const units = ['MSL-022', 'MSL-030', 'MSL-032', 'SL-30', 'SL-31', 'SL-32', 'SL-33', 'SL-34', 'SL-40', 'SL-41', 'SL-42', 'SL-43', 'SL-44', 'SL-47', 'SL-48'];
const accounts = ['D&WO', 'SAWCOD', 'Onshore Production', 'Offshore Production'];
const fields = ['Field North', 'Field South', 'Field East', 'Field West', 'Field Central'];
const crew = [['dev-emp-1', 'slickline_supervisor'], ['dev-emp-2', 'slickline_supervisor'], ['dev-emp-3', 'slickline_operator'], ['dev-emp-4', 'slickline_operator'], ['dev-emp-5', 'assistant_operator'], ['dev-emp-6', 'helper']];

const out = ['-- generated by scripts/make-dev-jobs.mjs (local development only)', "DELETE FROM job_crew WHERE job_id LIKE 'devjob-%';", "DELETE FROM job_services WHERE job_id LIKE 'devjob-%';", "DELETE FROM jobs WHERE id LIKE 'devjob-%';"];
for (let n = 1; n <= 120; n++) {
  const id = `devjob-${String(n).padStart(3, '0')}`;
  const day = 1 + Math.floor(rnd() * 300);
  const start = new Date(Date.UTC(2026, 0, day));
  const len = Math.floor(rnd() * 4);
  const end = new Date(start.getTime() + len * 86400000);
  const past = start < new Date(Date.UTC(2026, 9, 20));
  const status = past ? (rnd() < 0.05 ? 'canceled' : 'completed') : pick(['planned', 'planned', 'ongoing']);
  const iso = (d) => d.toISOString().slice(0, 10);
  const op = past && status === 'completed' ? Math.round((6 + rnd() * 40) * 10) / 10 : null;
  const npt = op && rnd() < 0.25 ? Math.round(rnd() * Math.min(op, 30) * 10) / 10 : 0;
  const failure = npt > 4 && rnd() < 0.6 ? 'yes' : op ? 'no' : null;
  const runsOk = op ? 1 + Math.floor(rnd() * 8) : null;
  const runsFail = op ? (failure === 'yes' ? 1 + Math.floor(rnd() * 2) : rnd() < 0.15 ? 1 : 0) : null;
  const rigUp = op ? `${iso(start)}T05:00:00.000Z` : null;
  const rigDown = op ? new Date(Date.parse(rigUp) + op * 3600000).toISOString() : null;
  const audit = op ? (rnd() < 0.3 ? 'yes' : 'no') : null;
  out.push(`INSERT INTO jobs (id, country, ticket_no, status, unit_number, start_date, end_date, location, field, rig, well, conveyance, rig_up_at, rig_down_at, runs_ok, runs_failed, npt_hours, failure, wellsite_audit, sdm_username, created_by, updated_by) VALUES (${[
    id, 'Saudi Arabia', `DV-${26000 + n}`, status, pick(units), iso(start), iso(end), pick(accounts), pick(fields), `RIG-${100 + Math.floor(rnd() * 40)}`, `W-${1000 + Math.floor(rnd() * 900)}`,
    pick(['Slickline', 'Braided line']), rigUp, rigDown, runsOk, runsFail, npt, failure, audit, pick(['NESR-90001', 'NESR-90003']), 'dev-seed', 'dev-seed',
  ].map(q).join(', ')});`);
  const svc = [...new Set([pick(services), ...(rnd() < 0.4 ? [pick(services)] : [])])];
  svc.forEach((s, i) => out.push(`INSERT INTO job_services (id, job_id, position, job_type_name) VALUES (${q(`${id}-s${i}`)}, ${q(id)}, ${i + 1}, ${q(s)});`));
  const team = [pick(crew.slice(0, 2)), pick(crew.slice(2, 4)), ...(rnd() < 0.5 ? [crew[4]] : [])];
  team.forEach(([e, role], i) => out.push(`INSERT INTO job_crew (id, job_id, employee_id, crew_role, slot) VALUES (${q(`${id}-c${i}`)}, ${q(id)}, ${q(e)}, ${q(role)}, 1);`));
}
fs.writeFileSync(new URL('./dev-jobs.sql', import.meta.url), out.join('\n') + '\n');
console.log(`${out.length} statements`);
